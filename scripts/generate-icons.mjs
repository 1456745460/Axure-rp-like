import { readFile, writeFile } from 'node:fs/promises'
import { h } from 'vue'
import { renderToString } from 'vue/server-renderer'
import * as icons from '@element-plus/icons-vue'

const packageUrl = new URL('../node_modules/@element-plus/icons-vue/package.json', import.meta.url)
const { version } = JSON.parse(await readFile(packageUrl, 'utf8'))
const entries = await Promise.all(Object.entries(icons).map(async ([name, icon]) => [
  name, (await renderToString(h(icon))).replace(/ data-v-[a-z0-9]+=""/g, '')
]))
const comment = `// Generated by npm run generate:icons from @element-plus/icons-vue ${version}; static SVGs keep HTML exports offline.\n`
await writeFile(new URL('../src/utils/iconSvgs.js', import.meta.url), `${comment}export const ICON_SVGS = ${JSON.stringify(Object.fromEntries(entries), null, 2)}\n`)
console.log(`Generated ${entries.length} offline SVG icons.`)
